import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const SOURCE_COMMIT_PATTERN = /^[0-9a-f]{40}$/;
const ATTESTED_FUNCTIONS = [
  "strategy-chat",
  "analyze-call",
  "mcp",
  "version",
];
const OUTPUT_PATH = resolve(
  "supabase/functions/_shared/edgeBuildManifest.generated.ts",
);

const checkOnly = process.argv.slice(2).includes("--check");
const unsupportedArgs = process.argv.slice(2).filter((arg) =>
  arg !== "--check"
);
if (unsupportedArgs.length > 0) {
  throw new Error(`Unsupported arguments: ${unsupportedArgs.join(", ")}`);
}

const sourceCommit = process.env.GITHUB_SHA ?? "";
if (!SOURCE_COMMIT_PATTERN.test(sourceCommit)) {
  throw new Error("GITHUB_SHA must be a full 40-character lowercase Git SHA");
}

try {
  execFileSync("git", ["cat-file", "-e", `${sourceCommit}^{commit}`], {
    stdio: "ignore",
  });
} catch {
  throw new Error(
    `GITHUB_SHA does not resolve to a Git commit: ${sourceCommit}`,
  );
}

const checkoutHead = execFileSync("git", ["rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();
if (checkoutHead !== sourceCommit) {
  throw new Error("GITHUB_SHA must equal the checked-out HEAD");
}

const worktreeStatus = execFileSync(
  "git",
  ["status", "--porcelain=v1", "--untracked-files=all"],
  { encoding: "utf8" },
).trim();
if (worktreeStatus) {
  throw new Error("Edge manifest generation requires a clean checkout");
}

const releaseDate = execFileSync(
  "git",
  [
    "show",
    "-s",
    "--format=%cd",
    "--date=format:%Y%m%d",
    sourceCommit,
  ],
  { encoding: "utf8", env: { ...process.env, TZ: "UTC" } },
).trim();

if (!/^[0-9]{8}$/.test(releaseDate)) {
  throw new Error(`Could not derive a UTC release date for ${sourceCommit}`);
}

const manifest = {
  release_id: `edge-${releaseDate}-${sourceCommit.slice(0, 12)}`,
  source_commit: sourceCommit,
  functions: Object.fromEntries(
    ATTESTED_FUNCTIONS.map((functionName) => [functionName, sourceCommit]),
  ),
};

const output = [
  "// Generated by scripts/generate-edge-build-manifest.mjs from GITHUB_SHA.",
  "// DO NOT EDIT OR COMMIT. CI overwrites this before checks and deployment.",
  `export const EDGE_BUILD_MANIFEST = ${
    JSON.stringify(manifest, null, 2)
  } as const;`,
  "",
].join("\n");

if (checkOnly) {
  let existing = "";
  try {
    existing = readFileSync(OUTPUT_PATH, "utf8");
  } catch {
    throw new Error(`Generated edge manifest is missing: ${OUTPUT_PATH}`);
  }
  if (existing !== output) {
    throw new Error("Generated edge manifest does not match GITHUB_SHA");
  }
  console.log(`Verified generated edge manifest for ${sourceCommit}`);
} else {
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, output, "utf8");
  console.log(`Generated edge build manifest for ${sourceCommit}`);
}
